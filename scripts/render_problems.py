#!/usr/bin/env python3
"""Render readable problem statements and copyable, source-grounded AI prompts."""
from __future__ import annotations

import argparse
from html import escape
from pathlib import Path

import markdown
import yaml

ROOT = Path(__file__).resolve().parents[1]
RESEARCH_GUIDANCE = """请协助研究上面的数学问题，并按以下要求工作：
1. 先打开并阅读所列原始来源，核对符号、归一化和全部适用假设。不能访问的资料请明确说明，不编造原文、定理编号或引用。
2. 查找后续进展，区分原作者的提问、已证明结论与本页提出的延伸任务。不能仅凭旧综述或未检得结果，就断言某个问题至今未解。
3. 以本轮任务为边界，先复现必要的已知计算，再尝试推进一个明确的子问题。新加的假设、使用的定理及其适用性都要写清楚。
4. 保留关键推导和可复现代码。将数值证据、形式计算、条件性论证和完整证明分开；主动检查特殊情形、退化极限及可能的反例。
5. 最后给出：本轮得到的可核验结论、对应证据、尚未证明的精确命题及下一步。不能完成时保留有效步骤，不把证明计划当作证明。"""


def prose(text: str) -> str:
    return markdown.markdown(text, extensions=['pymdownx.arithmatex'],
                             extension_configs={'pymdownx.arithmatex': {'generic': True}})


def render() -> str:
    data = yaml.safe_load((ROOT / 'data/problems.yml').read_text(encoding='utf-8'))
    papers = {p['id']: p for p in yaml.safe_load((ROOT / 'data/papers.yml').read_text(encoding='utf-8'))}
    problems = data['problems']
    ids = [p['id'] for p in problems]
    assert len(ids) == len(set(ids)), 'Problem IDs must be unique'
    cards = []
    for index, p in enumerate(problems, 1):
        links, references = [], []
        for source in p['sources']:
            url = papers[source['paper_id']]['url'] if 'paper_id' in source else source['url']
            assert url.startswith('https://'), url
            links.append(f'<li><a href="{escape(url, quote=True)}">{escape(source["label"])} ↗</a><span>{escape(source["location"])}</span></li>')
            references.append(f'- {source["label"]}\n  {source["location"]}\n  {url}')
        statement = (f'# {p["title"]}\n\n{p["attribution"]}\n\n{p["description"].strip()}\n\n'
                     f'目前进展与核查范围：{p["progress"]}\n\n{p.get("source_heading", "来源")}：\n' + '\n'.join(references)
                     + f'\n\n来源核对日期：{data["checked_on"]}；问题 ID：{p["id"]}')
        prompt = statement + '\n\n## 建议的本轮任务\n\n' + p['task'].strip() + '\n\n' + RESEARCH_GUIDANCE
        description = prose(p['description']).replace('\n', '\n    ')
        cards.append(f'''<article class="problem-card" id="{p['id']}">
  <div class="problem-topline"><span class="problem-number">PROBLEM {index:02}</span><span class="problem-status problem-status--{p['kind']}">{escape(p['status'])}</span></div>
  <h2><a href="#{p['id']}">{escape(p['title'])}</a></h2>
  <p class="problem-attribution">{escape(p['attribution'])}</p>
  <details class="problem-body" open><summary><span>问题描述</span><span class="problem-body-toggle"><span class="problem-body-open">收起</span><span class="problem-body-closed">展开</span><span class="problem-body-chevron" aria-hidden="true">⌃</span></span></summary>
  <div class="problem-description">{description}</div>
  <p class="problem-progress">{escape(p['progress'])}</p>
  <div class="problem-references"><h3>{escape(p.get('source_heading', '来源'))}</h3><ol class="problem-sources">{''.join(links)}</ol></div>
  <div class="problem-copy-row"><button type="button" data-copy-target="description-{p['id']}" hidden>复制问题描述</button><span class="problem-copy-status" role="status" aria-live="polite"></span></div>
  <textarea id="description-{p['id']}" class="problem-copy-text" aria-label="{escape(p['title'])}：可复制的问题描述" readonly hidden>{escape(statement)}</textarea>
  <details class="problem-prompt"><summary>建议的 AI 研究提示词 <span aria-hidden="true">＋</span></summary><p class="problem-prompt-intro">包含上述完整题意、公式和出处，并建议从以下任务开始。</p><div class="problem-task">{prose(p['task'].strip())}</div><div class="problem-copy-row"><button type="button" data-copy-target="prompt-{p['id']}" hidden>复制完整研究提示词</button><span class="problem-copy-status" role="status" aria-live="polite"></span></div><textarea id="prompt-{p['id']}" class="problem-copy-text" aria-label="{escape(p['title'])}：完整 AI 研究提示词" readonly hidden>{escape(prompt)}</textarea></details>
  </details>
</article>''')
    projects = ' · '.join(f'<a href="{escape(p["url"], quote=True)}">{escape(p["name"])}</a>' for p in data['projects'])
    prompt_links = ''.join(f'<li><a href="{escape(p["url"], quote=True)}">{escape(p["name"])} ↗</a><span>{escape(p["note"])}</span></li>' for p in data.get('prompt_references', []))
    return f'''---
title: 公开问题 / Open Problems
description: 可积系统公开问题的数学描述、已有进展、原始来源与 AI 研究提示词。
hide:
  - toc
---

<!-- Generated by scripts/render_problems.py. Edit data/problems.yml. -->
<div class="problems-page" data-problems>
<section class="problems-hero">
  <p class="problems-eyebrow">OPEN PROBLEMS <span>可积系统研究问题集</span></p>
  <h1>公开问题与研究进展<span>。</span></h1>
  <p class="problems-intro">汇集经典猜想与整理提出的研究问题，明确数学条件、目标和文献依据。</p>
  <div class="problems-hero-bottom"><p><strong>{len(problems):02}</strong> 个问题 <span>／</span> 来源核对 {data['checked_on']}</p></div>
</section>
<p class="problems-editor-note">题目注明原始出处或提出依据。已证明的情形和待核查范围随题说明；复制时保留公式与文献。</p>
<div class="problems-controls" hidden>
  <label class="problems-search"><span class="radar-visually-hidden">搜索问题、方程、方法或作者</span><span aria-hidden="true">⌕</span><input type="search" data-problem-query placeholder="搜索问题、方程、方法或作者…" autocomplete="off"></label>
  <div class="problems-results-line"><span data-problem-count role="status" aria-live="polite">{len(problems)} 个问题</span><button type="button" data-problem-reset hidden>清除搜索</button></div>
</div>
<div class="problems-list">
{chr(10).join(cards)}
</div>
<div class="problems-empty" data-problem-empty hidden><strong>没有找到匹配的问题</strong><p>试试 Dubrovin、奇数倍峰高或周期边界，或清除搜索查看全部问题。</p><button type="button" data-problem-clear>查看全部问题</button></div>
<footer class="problems-projects" id="reading-guide"><p>提示词与任务参考</p><ul class="problems-prompt-links">{prompt_links}</ul><p class="problems-projects-note">以上为公开项目的原始材料入口；逐题研究提示词为自行整理。First Proof 的评测题有已知的人类解答，与尚未解决的研究题有所不同。</p><p>参考项目</p><nav aria-label="参考的数学与 AI 研究项目">{projects}</nav></footer>
</div>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'docs/topics.md'
    content = render()
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit('Out of date: docs/topics.md; run scripts/render_problems.py')
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
    print(f'{"Checked" if args.check else "Rendered"} problem descriptions and AI research prompts.')


if __name__ == '__main__':
    main()
